@MainActor
@Suite struct SongGainTagsTests {
    @Test func aFlacFilesVorbisCommentsGiveAllFour() throws {
        let tags = try #require(try CountedFile(GainFixtures.gainFlac).tags(named: "a.flac"))
        #expect(tags.title == "Level")
        #expect(tags.replayGain == ReplayGain(trackGain: -6.2, trackPeak: 0.988553, albumGain: 1.5, albumPeak: 1))
    }

    @Test func anMP3FilesNamedFramesGiveThemInEitherCaseAndEitherEncoding() throws {
        let tags = try #require(try CountedFile(GainFixtures.gainMP3).tags(named: "a.mp3"))
        #expect(tags.title == "Level")
        // The album peak was never written: it stays unknown rather than being made up.
        #expect(tags.replayGain == ReplayGain(trackGain: -6.2, trackPeak: 0.988553, albumGain: 1.5, albumPeak: nil))
    }

    @Test func anMPEG4FilesNamedItemsGiveThem() throws {
        let tags = try #require(try CountedFile(GainFixtures.gainM4A).tags(named: "a.m4a"))
        #expect(tags.title == "Level")
        #expect(tags.replayGain == ReplayGain(trackGain: -6.2, trackPeak: 0.988553, albumGain: nil, albumPeak: 1))
    }

    @Test func aFileWithoutTheTagsSaysNothing() throws {
        #expect(try CountedFile(SongFixtures.flac2496).tags(named: "a.flac")?.replayGain == nil)
        #expect(try CountedFile(SongFixtures.vbrMP3).tags(named: "a.mp3")?.replayGain == nil)
        #expect(try CountedFile(SongFixtures.aac).tags(named: "a.m4a")?.replayGain == nil)
    }

    @Test func aValueThatIsNotANumberIsLeftOut() {
        var gain = GainTags()
        gain.take("REPLAYGAIN_TRACK_GAIN", "loud")
        gain.take("replaygain_track_peak", "nan")
        gain.take("REPLAYGAIN_REFERENCE_LOUDNESS", "89.0 dB")
        #expect(gain.values == nil)
        gain.take("replaygain_album_gain", " +3 dB")
        gain.take("REPLAYGAIN_ALBUM_GAIN", "-9 dB")
        #expect(gain.values == ReplayGain(trackGain: nil, trackPeak: nil, albumGain: 3, albumPeak: nil))
    }

    // MARK: A share asked about a song

    private func store() -> ShareStore {
        ShareStore(directory: FileManager.default.temporaryDirectory.appendingPathComponent("share-gain-\(UUID().uuidString)", isDirectory: true))
    }

    private func opened(_ share: FakeShare, _ store: ShareStore) async throws -> ShareMac {
        let mac = ShareMac(id: "share-gain", name: "NAS", files: share, playback: share, store: store)
        try await mac.open(timeout: .seconds(1))
        #expect(await eventually { !mac.isScanning })
        return mac
    }

    private func info(_ mac: ShareMac, _ ids: [Int64]) async throws -> [StreamInfo] {
        guard case .streamInfo(let items) = try await mac.request(.streamInfo(ids: ids, maxSampleRate: nil), timeout: .seconds(1)) else { return [] }
        return items
    }

    @Test func aShareAnswersWithWhatTheFileSaysEvenWhenItsIndexWasMadeBeforeTheTagsWereRead() async throws {
        let share = FakeShare()
        share.put("Album/01 Level.flac", GainFixtures.gainFlac)
        share.put("Album/02 Plain.flac", SongFixtures.flac2496)
        let store = store()
        defer { store.remove() }
        let first = try await opened(share, store)
        first.close()

        // An index as an earlier version of the app left it: every song there, none with gains.
        var library = try #require(store.library())
        let level = try #require(library.songs.first { $0.path == "Album/01 Level.flac" }?.id)
        let plain = try #require(library.songs.first { $0.path == "Album/02 Plain.flac" }?.id)
        #expect(library.songs.first { $0.id == level }?.tags.replayGain != nil)
        for index in library.songs.indices { library.songs[index].tags.replayGain = nil }
        store.save(library)

        let mac = try await opened(share, store)
        let expected = ReplayGain(trackGain: -6.2, trackPeak: 0.988553, albumGain: 1.5, albumPeak: 1)
        #expect(try await info(mac, [level]).first?.replayGain == expected)
        #expect(try await info(mac, [plain]).map(\.replayGain) == [nil])
        #expect(try await info(mac, [12345]).isEmpty)
        // Several songs asked about at once are answered from the index alone: no file is opened for that.
        share.forgetCounts()
        #expect(try await info(mac, [level, plain]).count == 2)
        #expect(share.readPaths.isEmpty)
        mac.close()
    }

    @Test func aShareThatCantBeReadAnswersWithWhatItsIndexHas() async throws {
        let share = FakeShare()
        share.put("Album/01 Level.flac", GainFixtures.gainFlac)
        let store = store()
        defer { store.remove() }
        let mac = try await opened(share, store)
        let level = try #require(store.library()?.songs.first?.id)
        share.failure = .timedOut
        let answer = try await info(mac, [level])
        #expect(answer.first?.replayGain == ReplayGain(trackGain: -6.2, trackPeak: 0.988553, albumGain: 1.5, albumPeak: 1))
        share.failure = nil
        mac.close()
    }
